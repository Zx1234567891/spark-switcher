#!/usr/bin/env bash
# Prepare the verified Python-engine GLM recipe without starting its ranks.

prepare_glm() (
    local upstream=https://github.com/MiaAI-Lab/GLM-5.3-Flash-EXL3-2x-DGX-Sparks-TensorFold.git
    local commit=bf5f94523a8251029cedae86bf61f8ce37fac218
    local model=Mia-AiLab/GLM-5.3-Flash-EXL3-4bpw-TensorFold
    local revision=078455ffe6472f9a52fbc1139f58b9db2881b25c
    local drafter=incoai/GLM-5.3-Flash-DFlash2
    local draft_revision=bf582e4eacc1810f76656d1811693ff6c6737d2a
    local registry=ghcr.io/miaai-lab/glm-5.3-flash-exl3-2x-dgx-sparks-tensorfold
    local registry_digest=sha256:99fe7496d7002fd8f2ca3b1beb0aa07513835cd09989ca657b65875d60f69956
    local image=tensorfold-glm53:v0.6.0
    local image_id=sha256:b925352f3515caddc1dde8abf33a621afad8133d2964a091184ad4842bfff7b6
    local checkout snapshot draft head_snapshot head_draft worker_snapshot worker_draft
    local model_suffix draft_suffix head_hub worker_hub worker_target fabric_peer configured_digest

    checkout=$(head_path "$(cfg models.glm.cwd)")
    snapshot=$(cfg models.glm.snapshot)
    draft=$(cfg models.glm.draft)
    configured_digest=$(cfg models.glm.digest)
    [[ "$configured_digest" == "$image_id" ]] || die "models.glm.digest must match the verified GLM image ID: $image_id"
    model_suffix="/models--${model//\//--}/snapshots/$revision"
    draft_suffix="/models--${drafter//\//--}/snapshots/$draft_revision"
    head_snapshot=$(head_path "$snapshot")
    head_draft=$(head_path "$draft")
    worker_snapshot=$(worker_path "$snapshot")
    worker_draft=$(worker_path "$draft")

    [[ "$head_snapshot" == /*"$model_suffix" && "$worker_snapshot" == /*"$model_suffix" ]] ||
        die "models.glm.snapshot must name the pinned snapshot under a Hugging Face hub directory"
    head_hub=${head_snapshot%"$model_suffix"}
    worker_hub=${worker_snapshot%"$model_suffix"}
    [[ "$head_hub" == /*/hub && "$worker_hub" == /*/hub ]] ||
        die "GLM snapshots must be inside a Hugging Face cache's hub directory"
    [[ "$head_draft" == "$head_hub$draft_suffix" && "$worker_draft" == "$worker_hub$draft_suffix" ]] ||
        die "GLM target and drafter must use the same Hugging Face hub directory on each Spark"
    worker_target=$(cfg worker.ssh_target)
    fabric_peer=$(cfg worker.roce_address)

    say "Preparing GLM source, pinned image and both checkpoint snapshots."
    ensure_checkout "$upstream" "$commit" "$checkout"
    ensure_image "$registry@$registry_digest" "$image" "$image_id"
    ensure_hf_snapshot "$model" "$revision" "$head_hub" "$worker_hub" \
        tokenizer.json chat_template.jinja generation_config.json processor_config.json quantization_config.json
    ensure_hf_snapshot "$drafter" "$draft_revision" "$head_hub" "$worker_hub"

    # Bash's %q preserves configured paths and SSH targets as literal values.
    # The upstream script only executes on the head; WORKER_HF_CACHE locates rank 1's cache.
    local temporary launch_config="$checkout/scripts/local.sh"
    if [[ -f "$launch_config" ]] &&
        ! head -n 1 "$launch_config" | grep -Fxq '# Generated by Spark Switcher deploy/glm.sh.'; then
        die "Use a clean GLM checkout directory or migrate the existing launch settings in $launch_config first."
    fi
    temporary=$(mktemp "$checkout/scripts/.spark-local.XXXXXX")
    if ! {
        printf '# Generated by Spark Switcher deploy/glm.sh.\n'
        printf 'WORKER=%q\nFABRIC_PEER=%q\n' "$worker_target" "$fabric_peer"
        printf 'HF_CACHE=%q\nWORKER_HF_CACHE=%q\n' "${head_hub%/hub}" "${worker_hub%/hub}"
        printf 'MODEL_ID=%q\nMODEL_REVISION=%q\n' "$model" "$revision"
        printf 'DFLASH2_ID=%q\nDFLASH2_REVISION=%q\n' "$drafter" "$draft_revision"
        printf 'IMAGE=%q\nIMAGE_TAG=%q\nIMAGE_DIGEST=%q\n' "$image" v0.6.0-789e8f3bdfa2 "$registry_digest"
        printf '%s\n' 'TP=2' 'WORKER2=' 'WORKER_WEIGHTS=copy' 'ABLIT=0' \
            'TF_VERSION=v0.6.0' 'CONTAINER_NAME=glm53-flash-tf' 'DRAFTER=dflash2' 'DENSE=q4' 'KV=fp8' \
            'HOST=127.0.0.1' 'PORT=8888' 'SERVED_NAME=GLM-5.3-Flash-EXL3' \
            'CONTEXT=1048576' 'PARALLEL=4' 'MAX_TOKENS=131072' 'THINKING=1' 'VISION=1' \
            'PREPARE=0' 'PULL=0' 'export HF_HUB_OFFLINE=1' 'export TRANSFORMERS_OFFLINE=1' \
            'export HF_DATASETS_OFFLINE=1' 'export TENSORFOLD_NO_UPDATE_CHECK=1'
    } > "$temporary"; then
        rm -f -- "$temporary"
        die "Could not write GLM launch configuration"
    fi
    chmod 0600 "$temporary"
    mv -f -- "$temporary" "$launch_config"
    say "GLM prepared. The controller can launch both ranks with the upstream start.sh."
)
